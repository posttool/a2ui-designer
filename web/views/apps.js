// Connected apps console: register MCP servers (Streamable HTTP), browse their
// tools, fill a tool's arguments in a generated A2UI form, call it, and import
// the result as a Sample. Routes: /apps and /apps/:aid.
import {cached, del, get, patch, post} from '../components/api.js';
import {chip} from '../components/badges.js';
import {emptyState, fmtTime, h, icon, mount, relTime, spinner} from '../components/dom.js';
import {jsonTree} from '../components/jsontree.js';
import {navigate} from '../components/store.js';
import {confirmDialog, drawer, toast} from '../components/ui.js';
import {mountSurface} from '../renderer/host.js';

const KIND_LABEL = {
  demo: 'Demo',
  remote: 'Remote MCP'
};

export async function render(root, params, ctx) {
  const aid = params.aid || null;
  let alive = true;
  let apps = [];
  const page = h('div.page.page-apps');
  root.appendChild(page);

  if (!aid) {
    await renderList();
  } else {
    await renderDetail();
  }
  return () => {
    alive = false;
  };

  // ---------------------------------------------------------------- list
  async function renderList() {
    const grid = h('div.app-grid#app-grid', spinner('Loading apps\u2026'));
    mount(
        page,
        h('div.page-head',
          h('div', h('h1', 'Connected apps'),
            h('p.lede',
              'MCP servers whose tools produce real input data. Pick a tool, fill its arguments in a form generated by your constitution, and import the result as a sample.')),
          h('div.page-actions',
            h('button.btn.btn-ghost#add-demo-app',
              {type: 'button', onclick: (e) => addDemo(e.currentTarget)},
              icon('science'), 'Add demo app'),
            h('button.btn.btn-primary#add-app',
              {type: 'button', onclick: () => openAppDrawer(null)}, icon('add'),
              'Add app'))),
        grid);
    try {
      const res = await get('/api/connected_apps');
      apps = res.apps || [];
    } catch (e) {
      mount(grid, emptyState('Could not load connected apps', e.message));
      return;
    }
    if (!alive) return;
    if (!apps.length) {
      grid.classList.add('is-empty');
      mount(
          grid,
          emptyState(
              'No connected apps yet',
              'Register an MCP server by URL, or add the bundled demo app (pharmacy, calendar and shop tools with deterministic fake data) to try the flow.',
              h('button.btn.btn-primary#add-demo-empty',
                {type: 'button', onclick: (e) => addDemo(e.currentTarget)},
                icon('science'), 'Add demo app'),
              h('button.btn.btn-ghost',
                {type: 'button', onclick: () => openAppDrawer(null)},
                icon('add'), 'Add app')));
      return;
    }
    mount(grid, apps.map(appCard));
  }

  function appCard(a) {
    return h(
        'article.app-card', {dataset: {appId: a.id}, class: `as-${a.status}`},
        h('a.app-card-link', {href: `/apps/${a.id}`, 'aria-label': a.name}),
        h('div.app-card-top', h('span.app-icon', icon('extension')),
          h('div.app-card-title', h('div.app-name', {title: a.name}, a.name),
            h('div.app-url', a.url || '')),
          kindChip(a.kind)),
        a.description ? h('p.app-desc', a.description) : null,
        h('div.app-card-foot', appStatus(a),
          h('span.muted',
            `${a.tool_count ?? (a.tools || []).length} tool${
                (a.tool_count ?? (a.tools || []).length) === 1 ? '' : 's'}`),
          h('span.grow'),
          h('span.muted.small',
            a.last_sync_at ? `synced ${relTime(a.last_sync_at)}` :
                             'never synced')),
        a.status === 'error' && a.last_error ?
            h('p.app-error', icon('error'), h('span', a.last_error)) :
            null);
  }

  async function addDemo(btn) {
    if (btn) btn.disabled = true;
    try {
      const {app} = await post('/api/connected_apps/demo');
      toast(`Added \u201c${app.name}\u201d`, 'good');
      navigate(`/apps/${app.id}`);
    } finally {
      if (btn) btn.disabled = false;
    }
  }

  // ---------------------------------------------------------- add / edit
  function openAppDrawer(app) {
    const editing = !!app;
    const name = h('input.input#app-name', {
      value: app ? app.name : '',
      placeholder: 'e.g. Pharmacy (staging)',
      autofocus: true
    });
    const url = h('input.input#app-url', {
      value: app ? app.url : '',
      placeholder: 'https://example.com/mcp',
      type: 'url',
      disabled: app && app.kind === 'demo'
    });
    const desc =
        h('textarea.input#app-description',
          {rows: 2, placeholder: 'Optional \u2014 what the app is for'},
          app ? app.description || '' : '');
    const rowsEl = h('div.header-rows#app-headers');
    const rows = [];
    const addRow = (k = '', v = '', masked = false) => {
      const kIn = h(
          'input.input.input-sm.header-key',
          {value: k, placeholder: 'Header name', 'aria-label': 'Header name'});
      const vIn = h('input.input.input-sm.header-val', {
        value: v,
        placeholder: masked ? 'unchanged' : 'Value',
        type: masked ? 'password' : 'text',
        'aria-label': 'Header value',
      });
      const row = {kIn, vIn, masked, original: v};
      const el =
          h('div.header-row', kIn, vIn,
            h('button.icon-btn', {
              type: 'button',
              'aria-label': 'Remove header',
              onclick: () => {
                rows.splice(rows.indexOf(row), 1);
                el.remove();
              }
            },
              icon('close')));
      row.el = el;
      rows.push(row);
      rowsEl.appendChild(el);
    };
    Object.entries((app && app.headers_masked) || {})
        .forEach(([k, v]) => addRow(k, v, true));
    const err = h('p.form-error');
    const saveBtn =
        h('button.btn.btn-primary#app-save', {type: 'button', onclick: save},
          editing ? 'Save changes' : 'Save & sync');
    const d = drawer({
      title: editing ? `Edit ${app.name}` : 'Add connected app',
      id: 'app-drawer',
      body: h(
          'div.app-form', h('label.field', h('span.field-label', 'Name'), name),
          h('label.field', h('span.field-label', 'MCP server URL'), url,
            h('span.help',
              'Streamable HTTP endpoint. DCB lists its tools on save and calls them server-side.')),
          h('label.field', h('span.field-label', 'Description'), desc),
          h('div.field', h('span.field-label', 'Headers'),
            h('p.help',
              'Sent with every request, e.g. Authorization. Saved values are masked; leave a masked value as is to keep it.'),
            rowsEl,
            h('button.link-btn#app-add-header',
              {type: 'button', onclick: () => addRow()}, '+ Add header')),
          err,
          h('div.drawer-actions', saveBtn,
            h('button.btn.btn-ghost',
              {type: 'button', onclick: () => d.close()}, 'Cancel'))),
    });
    async function save() {
      err.textContent = '';
      const body = {
        name: name.value.trim(),
        url: url.value.trim(),
        description: desc.value.trim(),
        headers: {}
      };
      for (const r of rows) {
        const k = r.kIn.value.trim();
        if (!k) continue;
        // Untouched masked values round-trip as the masked form (kept).
        body.headers[k] = r.masked && !r.vIn.value ? r.original : r.vIn.value;
      }
      if (!body.name) {
        err.textContent = 'Name the app.';
        name.focus();
        return;
      }
      if (!body.url && !(app && app.kind === 'demo')) {
        err.textContent = 'Enter the MCP server URL.';
        url.focus();
        return;
      }
      if (app && app.kind === 'demo') delete body.url;
      saveBtn.disabled = true;
      saveBtn.classList.add('busy');
      try {
        const res = editing ?
            await patch(`/api/connected_apps/${app.id}`, body) :
            await post('/api/connected_apps', body);
        const saved = res.app;
        d.close();
        if (saved.status === 'error')
          toast(
              `Saved, but sync failed: ${saved.last_error || 'error'}`, 'warn',
              7000);
        else
          toast(
              `${editing ? 'Saved' : 'Added'} \u201c${
                  saved.name}\u201d \u2014 ${
                  saved.tool_count ?? (saved.tools || []).length} tools`,
              'good');
        if (editing) {
          render2();
        } else {
          navigate(`/apps/${saved.id}`);
        }
      } finally {
        saveBtn.disabled = false;
        saveBtn.classList.remove('busy');
      }
    }
  }

  function render2() {
    mount(page);
    if (aid)
      renderDetail();
    else
      renderList();
  }

  // -------------------------------------------------------------- detail
  async function renderDetail() {
    mount(page, spinner('Loading app\u2026'));
    let app;
    let projects = [];
    let viewports = [];
    let sets = [];
    try {
      const [a, p, v, s] = await Promise.all([
        get(`/api/connected_apps/${aid}`),
        get('/api/projects', {quiet: true}).catch(() => ({projects: []})),
        cached('/api/viewports').catch(() => []),
        get('/api/sample_sets', {quiet: true}).catch(() => ({sets: []})),
      ]);
      app = a.app;
      projects = (p.projects || []).filter((x) => !x.archived);
      viewports = Array.isArray(v) ? v : (v.viewports || []);
      sets = s.sets || [];
    } catch (e) {
      mount(
          page, h('div.crumbs', h('a', {href: '/apps'}, 'Connected apps')),
          emptyState('App not found', e.message));
      return;
    }
    if (!alive) return;
    const tools = app.tools || [];
    let selTool = null;
    const toolList = h('div.tool-list#tool-list');
    const toolPane = h('div.tool-pane#tool-pane');

    const syncBtn =
        h('button.btn.btn-ghost#app-sync', {
          type: 'button',
          onclick: async (e) => {
            const b = e.currentTarget;
            b.disabled = true;
            b.classList.add('busy');
            try {
              const res = await post(`/api/connected_apps/${app.id}/sync`);
              toast(
                  res.app.status === 'error' ?
                      `Sync failed: ${res.app.last_error || 'error'}` :
                      `Synced \u2014 ${(res.app.tools || []).length} tools`,
                  res.app.status === 'error' ? 'bad' : 'good');
              render2();
            } finally {
              b.disabled = false;
              b.classList.remove('busy');
            }
          }
        },
          icon('sync'), 'Sync');

    mount(
        page,
        h('div.crumbs', h('a', {href: '/apps'}, 'Connected apps'),
          h('span', '/'), h('span', app.name)),
        h('div.page-head',
          h('div',
            h('div.title-row', h('h1', app.name), kindChip(app.kind),
              appStatus(app)),
            h('p.lede.small',
              [
                app.url,
                app.server_info && app.server_info.name ?
                    `${app.server_info.name}${
                        app.server_info.version ?
                            ` ${app.server_info.version}` :
                            ''}` :
                    null,
                app.server_info && app.server_info.protocol_version ?
                    `MCP ${app.server_info.protocol_version}` :
                    null,
                app.last_sync_at ? `synced ${fmtTime(app.last_sync_at)}` : null,
              ].filter(Boolean)
                  .join(' \u00b7 ')),
            app.description ? h('p.lede.small', app.description) : null),
          h('div.page-actions', syncBtn,
            h('button.btn.btn-ghost#app-edit',
              {type: 'button', onclick: () => openAppDrawer(app)}, icon('edit'),
              'Edit'),
            h('button.btn.btn-ghost.btn-danger-quiet#app-delete', {
              type: 'button',
              onclick: async () => {
                if (!(await confirmDialog(
                        'Delete connected app?',
                        `\u201c${
                            app.name}\u201d will be removed. Samples already imported from it stay in the library.`,
                        {confirmLabel: 'Delete', danger: true})))
                  return;
                await del(`/api/connected_apps/${app.id}`);
                toast('App deleted', 'good');
                navigate('/apps');
              }
            },
              icon('delete'), 'Delete'))),
        app.status === 'error' && app.last_error ?
            h('div.banner.banner-warn', icon('error'),
              h('span.banner-text', `Last sync failed: ${app.last_error}`)) :
            null,
        tools.length ? h('div.app-detail', toolList, toolPane) :
                       emptyState(
                           'No tools',
                           app.status === 'error' ?
                               'Fix the URL or headers and sync again.' :
                               'This server lists no tools. Sync to refresh.'));
    if (!tools.length) return;

    function drawToolList() {
      mount(
          toolList, h('div.sets-title', `Tools (${tools.length})`),
          tools.map(
              (t) =>
                  h('button.tool-item', {
                    type: 'button',
                    id: `tool-${t.name}`,
                    class: selTool === t ? 'on' : '',
                    onclick: () => selectTool(t)
                  },
                    h('span.tool-item-title', t.title || t.name),
                    t.title && t.title !== t.name ?
                        h('code.tool-item-name', t.name) :
                        null,
                    t.description ? h('span.tool-item-desc', t.description) :
                                    null)));
    }

    function selectTool(t) {
      selTool = t;
      const u = new URL(location.href);
      u.searchParams.set('tool', t.name);
      history.replaceState(null, '', u.pathname + u.search);
      drawToolList();
      mount(toolPane, toolFlow(app, t, {projects, viewports, sets}));
    }

    drawToolList();
    const want = ctx.url.searchParams.get('tool');
    selectTool(tools.find((t) => t.name === want) || tools[0]);
  }

  // ------------------------------------------------- per-tool import flow
  function toolFlow(app, tool, {projects, viewports, sets}) {
    let args = defaultArgs(tool.input_schema);
    let result = null;  // {result, latency_ms}
    let formRes = null;
    let surface = null;

    const lastPid = localStorage.getItem('a2uid.apps.project') || '';
    const projSel = h(
        'select.input.input-sm#form-project',
        h('option', {value: ''}, 'No project (Basic catalog)'),
        projects.map(
            (p) => h(
                'option', {value: p.id, selected: p.id === lastPid}, p.name)));
    const vpSel =
        h('select.input.input-sm#form-viewport',
          (viewports.length ? viewports : [{id: 'phone', label: 'Phone'}])
              .map(
                  (v) =>
                      h('option', {value: v.id, selected: v.id === 'phone'},
                        `${v.label || v.id}${
                            v.width ? ` ${v.width}\u00d7${v.height}` : ''}`)));
    const simple = h('input#form-simple', {
      type: 'checkbox',
      checked: localStorage.getItem('a2uid.apps.simpleForm') === '1'
    });
    simple.addEventListener(
        'change',
        () => localStorage.setItem(
            'a2uid.apps.simpleForm', simple.checked ? '1' : '0'));
    const genBtn =
        h('button.btn.btn-primary.btn-sm#form-generate',
          {type: 'button', onclick: () => generate()}, icon('auto_awesome'),
          'Generate form');
    const formMeta = h('div.form-meta#form-meta');
    const formHost = h('div.form-host#form-host');
    const jsonBox = h('div.args-json#args-json', {hidden: true});
    const resultEl = h('div.call-result#call-result');
    const importEl = h('div.import-box#import-box');

    const schemaDetails =
        h('details.tool-schema', h('summary', 'Input schema'),
          jsonTree(tool.input_schema || {}, {collapseDepth: 3}));

    const el = h(
        'div.tool-flow', {dataset: {tool: tool.name}},
        h('div.tool-head', h('h2', tool.title || tool.name),
          tool.title && tool.title !== tool.name ? h('code', tool.name) : null),
        tool.description ? h('p.tool-desc', tool.description) : null,
        schemaDetails,
        tool.output_schema ?
            h('details.tool-schema', h('summary', 'Output schema'),
              jsonTree(tool.output_schema, {collapseDepth: 2})) :
            null,
        h('section.flow-step',
          h('div.flow-step-head', h('span.flow-num', '1'),
            h('h3', 'Fill the arguments')),
          h('div.form-controls', h('label.inline-label', 'Project', projSel),
            h('label.inline-label', 'Viewport', vpSel),
            h('label.check.small',
              {title: 'Deterministic form from the input schema, no LLM call'},
              simple, 'Simple form'),
            h('span.grow'), genBtn,
            h('button.btn.btn-quiet.btn-sm#args-json-toggle',
              {type: 'button', onclick: () => toggleJson()},
              icon('data_object'), 'Edit args as JSON')),
          h('p.help',
            'The form is generated like any output: with the chosen project\u2019s constitution, catalog and theme (or the Basic catalog with no constitution).'),
          formMeta, formHost, jsonBox),
        h('section.flow-step',
          h('div.flow-step-head', h('span.flow-num', '2'),
            h('h3', 'Call the tool')),
          resultEl),
        h('section.flow-step',
          h('div.flow-step-head', h('span.flow-num', '3'),
            h('h3', 'Import as a sample')),
          importEl));
    drawResult();
    drawImport();
    return el;

    function projectTheme() {
      const p = projects.find((x) => x.id === projSel.value);
      return p && p.settings ? p.settings.theme : undefined;
    }

    async function generate() {
      localStorage.setItem('a2uid.apps.project', projSel.value);
      genBtn.disabled = true;
      genBtn.classList.add('busy');
      mount(formMeta);
      mount(
          formHost,
          h('div.form-wait',
            spinner(
                simple.checked ? 'Building form\u2026' :
                                 'Generating the form with Gemini\u2026')));
      try {
        const body = {tool: tool.name, viewport: vpSel.value, prefill: args};
        if (projSel.value) body.project_id = projSel.value;
        if (simple.checked) body.mode = 'schema';
        formRes = await post(`/api/connected_apps/${app.id}/form`, body);
        drawForm();
      } catch (e) {
        mount(
            formHost,
            h('p.form-error', `Could not build the form: ${e.message}`));
      } finally {
        genBtn.disabled = false;
        genBtn.classList.remove('busy');
      }
    }

    function drawForm() {
      if (surface) {
        try {
          surface.destroy();
        } catch (_) { /* ignore */
        }
        surface = null;
      }
      const r = formRes;
      const errs = (r.validation && r.validation.errors) || [];
      mount(
          formMeta,
          h('div.chip-row',
            chip(
                r.mode === 'schema' ? 'Schema form' : 'LLM form',
                r.mode === 'schema' ? 'chip-quiet' : 'tint-3'),
            r.model ? h('span.muted.small', r.model) : null,
            r.latency_ms != null ?
                h('span.muted.small', `${(r.latency_ms / 1000).toFixed(1)} s`) :
                null,
            r.validation && r.validation.ok === false ?
                chip(
                    `${errs.length} validation issue${
                        errs.length === 1 ? '' : 's'}`,
                    'c-bad') :
                null),
          r.fallback_reason ?
              h('div.callout.callout-warn', icon('info'),
                h('div', h('strong', 'Fell back to the schema form. '),
                  r.fallback_reason)) :
              null,
          errs.length ?
              h('details.form-errs', h('summary.small', 'Validation details'),
                h('ul.errors',
                  errs.map(
                      (e) =>
                          h('li', h('code', e.path || '/'), ' ', e.message)))) :
              null);
      const vp = viewports.find((v) => v.id === vpSel.value);
      const box =
          h('div.form-surface',
            {style: {width: `${Math.min(vp ? vp.width : 412, 720)}px`}});
      mount(formHost, box);
      const submitEvent = (r.form && r.form.submit_event) || 'submit';
      surface = mountSurface(box, r.messages || [], {
        interactive: true,
        theme: projectTheme(),
        onAction: (payload) => {
          const a = payload && payload.action;
          if (!a || a.name !== submitEvent) {
            if (a)
              toast(
                  `Form action \u201c${a.name}\u201d (not the submit event)`,
                  'info', 2500);
            return;
          }
          args = argsFromContext(
              a.context || {}, r.form && r.form.schema || tool.input_schema);
          callTool();
        },
      });
      if (surface.meta && (surface.meta.errors || []).length)
        formMeta.appendChild(
            h('p.small.c-bad', surface.meta.errors.join(' \u00b7 ')));
    }

    function toggleJson() {
      if (!jsonBox.hidden) {
        jsonBox.hidden = true;
        return;
      }
      const ta =
          h('textarea.input.code-input#args-json-input',
            {rows: 10, spellcheck: 'false'}, JSON.stringify(args, null, 2));
      const err = h('p.form-error');
      mount(
          jsonBox, ta, err,
          h('div.row-btns',
            h('button.btn.btn-primary.btn-sm#args-json-call', {
              type: 'button',
              onclick: () => {
                try {
                  const v = JSON.parse(ta.value || '{}');
                  if (!v || typeof v !== 'object' || Array.isArray(v))
                    throw new Error('arguments must be a JSON object');
                  args = v;
                } catch (e) {
                  err.textContent = `Invalid JSON: ${e.message}`;
                  return;
                }
                callTool();
              }
            },
              icon('play_arrow'), 'Call with these args'),
            h('button.btn.btn-quiet.btn-sm',
              {type: 'button', onclick: () => (jsonBox.hidden = true)},
              'Close')));
      jsonBox.hidden = false;
      ta.focus();
    }

    async function callTool() {
      mount(resultEl, spinner(`Calling ${tool.name}\u2026`));
      try {
        result = await post(
            `/api/connected_apps/${app.id}/call`, {tool: tool.name, args});
        // The server coerces args to the schema; keep what was actually sent.
        if (result && result.args && typeof result.args === 'object')
          args = result.args;
      } catch (e) {
        result = null;
        mount(
            resultEl,
            h('div.callout.callout-bad', icon('error'),
              h('div', h('strong', 'Call failed. '), e.message)),
            argsSummary());
        drawImport();
        return;
      }
      drawResult();
      drawImport();
      resultEl.scrollIntoView({behavior: 'smooth', block: 'nearest'});
    }

    function argsSummary() {
      return h(
          'details.args-sent', h('summary.small', 'Arguments sent'),
          jsonTree(args, {collapseDepth: 2}));
    }

    function drawResult() {
      if (!result) {
        mount(
            resultEl,
            h('p.muted.small',
              'Submit the form (or call with JSON args) to see the tool\u2019s result here.'));
        return;
      }
      const r = result.result || {};
      const body = r.structured != null ? r.structured : parseMaybe(r.text);
      mount(
          resultEl,
          h('div.chip-row',
            r.is_error ? chip('Tool error', 'c-bad') : chip('OK', 'v-good'),
            result.latency_ms != null ?
                h('span.muted.small', `${result.latency_ms} ms`) :
                null,
            r.structured != null ? h('span.muted.small', 'structured content') :
                                   h('span.muted.small', 'text content')),
          h('div.result-tree', {class: r.is_error ? 'is-error' : ''},
            typeof body === 'string' ? h('pre.code', body) :
                                       jsonTree(body, {collapseDepth: 2})),
          argsSummary());
    }

    function drawImport() {
      const intent =
          h('textarea.input#import-intent', {
            rows: 3,
            placeholder:
                'What does the person want from this data? e.g. \u201cSee which refills are due this week and reorder the urgent one.\u201d'
          },
            tool.description || '');
      const title = h('input.input#import-title', {
        value: `${tool.title || tool.name} \u2014 ${app.name}`,
      });
      const setSel =
          h('select.input#import-set', h('option', {value: ''}, 'No set'),
            sets.map((s) => h('option', {value: s.id}, s.name)));
      const btn =
          h('button.btn.btn-primary#import-sample', {
            type: 'button',
            disabled: !result || (result.result && result.result.is_error),
            onclick: async () => {
              if (!intent.value.trim()) {
                toast(
                    'Describe the intent \u2014 the generator needs it.',
                    'warn');
                intent.focus();
                return;
              }
              btn.disabled = true;
              btn.classList.add('busy');
              try {
                const body = {
                  tool: tool.name,
                  args,
                  result: result.result,
                  intent: intent.value.trim(),
                  title: title.value.trim() || undefined,
                };
                if (setSel.value) body.set_id = setSel.value;
                const {sample} =
                    await post(`/api/connected_apps/${app.id}/import`, body);
                toast(
                    [
                      `Imported \u201c${sample.title}\u201d. `,
                      h('a.toast-link', {
                        href: setSel.value ?
                            `/data?set=${setSel.value}` :
                            `/data?q=${encodeURIComponent(sample.title)}`
                      },
                        'Open in Data library')
                    ],
                    'good', 8000);
              } finally {
                btn.disabled = false;
                btn.classList.remove('busy');
              }
            }
          },
            icon('download'), 'Import as sample');
      mount(
          importEl,
          !result ?
              h('p.muted.small', 'Call the tool first.') :
              result.result && result.result.is_error ?
              h('p.small.c-bad',
                'The tool returned an error \u2014 fix the arguments and call again.') :
              null,
          h('div.import-fields', {class: result ? '' : 'is-disabled'},
            h('label.field', h('span.field-label', 'Intent'), intent),
            h('div.form-row',
              h('label.field.grow', h('span.field-label', 'Title'), title),
              h('label.field', h('span.field-label', 'Add to sample set'),
                setSel)),
            h('p.help',
              'The app becomes the category and the tool the subcategory. Runs on MCP samples generate the input form and the result, as a pair.'),
            btn));
    }
  }
}

