function parseMaybe(text) {
  if (text == null) return null;
  try {
    return JSON.parse(text);
  } catch (_) {
    return String(text);
  }
}

/** Initial args: schema defaults (and nothing else). */
function defaultArgs(schema) {
  const out = {};
  const props = (schema && schema.properties) || {};
  for (const [k, p] of Object.entries(props)) {
    if (p && p.default !== undefined) out[k] = p.default;
  }
  return out;
}

/**
 * Tool arguments from a submit action's context: `context.form` when it is an
 * object, else the context itself. Keys are limited to the schema's properties
 * when it declares any, and values are coerced to the declared JSON types
 * (form fields bind strings).
 */
export function argsFromContext(context, schema) {
  let raw = context && typeof context.form === 'object' && context.form &&
          !Array.isArray(context.form) ?
      context.form :
      {...(context || {})};
  const props = (schema && schema.properties) || null;
  const out = {};
  for (const [k, v] of Object.entries(raw)) {
    if (props && Object.keys(props).length && !(k in props)) continue;
    const c = coerce(v, props ? props[k] : null);
    if (c === undefined) continue;
    out[k] = c;
  }
  return out;
}

function coerce(v, p) {
  if (v === '' || v == null) return undefined;
  const t =
      p && (Array.isArray(p.type) ? p.type.find((x) => x !== 'null') : p.type);
  if (!t) return v;
  if ((t === 'integer' || t === 'number') && typeof v === 'string') {
    const n = Number(v);
    return Number.isFinite(n) ? (t === 'integer' ? Math.round(n) : n) : v;
  }
  if (t === 'boolean' && typeof v === 'string') return v === 'true';
  if (t === 'array' && !Array.isArray(v)) {
    if (typeof v === 'string')
      return v.split(',').map((s) => s.trim()).filter(Boolean);
    return [v];
  }
  if (t === 'string' && Array.isArray(v) && v.length <= 1) return v[0];
  return v;
}
